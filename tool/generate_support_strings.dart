// Builds lib/src/support/support_strings_table.g.dart from the shared Support
// translation table (Localization/support-strings.json, the same file the
// iOS, Android and React Native SDKs use). Plural keys become
// `key#<cldr category>`.
//
//     dart run tool/generate_support_strings.dart [path/to/support-strings.json]
import 'dart:convert';
import 'dart:io';

void main(List<String> args) {
  final root = File.fromUri(Platform.script).parent.parent.path;
  final source = args.isNotEmpty
      ? args.first
      : '$root/Localization/support-strings.json';
  final table =
      jsonDecode(File(source).readAsStringSync()) as Map<String, dynamic>;
  final keys = table['keys'] as Map<String, dynamic>;
  final translations = table['translations'] as Map<String, dynamic>;
  final languages = <String, Map<String, dynamic>>{
    'en': {for (final e in keys.entries) e.key: (e.value as Map)['en']},
    for (final e in translations.entries)
      e.key: Map<String, dynamic>.from(e.value as Map),
  };
  final names = languages.keys.toList()..sort();

  String quote(String s) =>
      "'${s.replaceAll(r'\', r'\\').replaceAll("'", r"\'").replaceAll(r'$', r'\$').replaceAll('\n', r'\n')}'";

  final out = StringBuffer()
    ..writeln(
      '// Generated by tool/generate_support_strings.dart from '
      'Localization/support-strings.json. Do not edit.',
    )
    ..writeln('// dart format off')
    ..writeln()
    ..writeln('/// Every language the help chat ships, as BCP 47 tags.')
    ..writeln('const supportLanguages = <String>[')
    ..writeln('  ${names.map(quote).join(', ')},')
    ..writeln('];')
    ..writeln()
    ..writeln('/// Language → key → text. Plural keys are `key#<category>`.')
    ..writeln('const supportStringsTable = <String, Map<String, String>>{');
  for (final lang in names) {
    final strings = languages[lang]!;
    out.writeln('  ${quote(lang)}: {');
    for (final key in keys.keys) {
      final value = strings[key];
      if (value == null) {
        stderr.writeln('$lang: missing $key');
        exitCode = 1;
        continue;
      }
      if (value is Map) {
        for (final form in value.entries) {
          out.writeln(
            '    ${quote('$key#${form.key}')}: ${quote(form.value as String)},',
          );
        }
      } else {
        out.writeln('    ${quote(key)}: ${quote(value as String)},');
      }
    }
    out.writeln('  },');
  }
  out.writeln('};');
  final target = File('$root/lib/src/support/support_strings_table.g.dart');
  target.writeAsStringSync(out.toString());
  stdout.writeln(
    '${names.length} languages, ${keys.length} keys -> ${target.path}',
  );
}
